#!/usr/bin/env bash
# install-hooks.sh — wire the leak check into this fork, in its LOCAL git
# config only (nothing is committed, nothing outside the fork is touched):
#   core.hooksPath        = <this tooling directory>/hooks (absolute)
#   forkleak.patternsFile = --patterns F, or
#                           ${XDG_STATE_HOME:-$HOME/.local/state}/ai-sdlc/gufo-fork-leak.patterns
#
#   install-hooks.sh [--patterns F] [--check]
#
# --check prints the two settings and exits non-zero if either is not what
# this script would set, or the patterns file is absent or empty. The
# patterns file is generated by the private repository's fork-patterns verb;
# without it every leak check (and so every push) fails closed.
set -uo pipefail

ih_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
pat="${XDG_STATE_HOME:-$HOME/.local/state}/ai-sdlc/gufo-fork-leak.patterns" check=0
while [ $# -gt 0 ]; do
  case "$1" in
    --patterns) [ -n "${2:-}" ] || { echo "install-hooks: --patterns needs a file" >&2; exit 2; }; pat="$2"; shift 2 ;;
    --check) check=1; shift ;;
    *) echo "install-hooks: usage: install-hooks.sh [--patterns F] [--check]" >&2; exit 2 ;;
  esac
done
common="$(git -C "$ih_dir" rev-parse --path-format=absolute --git-common-dir 2>/dev/null)" \
  || { echo "install-hooks: $ih_dir is not inside the fork's git repository" >&2; exit 2; }
hooks="$ih_dir/hooks"
if [ "$check" = 1 ]; then
  rc=0
  h="$(git --git-dir="$common" config --local --get core.hooksPath)"; p="$(git --git-dir="$common" config --local --get forkleak.patternsFile)"
  printf 'core.hooksPath=%s\nforkleak.patternsFile=%s\n' "$h" "$p"
  [ "$h" = "$hooks" ] || { echo "install-hooks: core.hooksPath is not $hooks" >&2; rc=1; }
  [ "$p" = "$pat" ] || { echo "install-hooks: forkleak.patternsFile is not $pat" >&2; rc=1; }
  [ -s "$pat" ] || { echo "install-hooks: the patterns file $pat is absent or empty" >&2; rc=1; }
  exit "$rc"
fi
chmod +x "$hooks/pre-push" "$ih_dir/leakcheck.sh" "$ih_dir/build.sh" 2>/dev/null
git --git-dir="$common" config --local core.hooksPath "$hooks" || exit 1
git --git-dir="$common" config --local forkleak.patternsFile "$pat" || exit 1
printf 'install-hooks: core.hooksPath=%s\ninstall-hooks: forkleak.patternsFile=%s\n' "$hooks" "$pat"
[ -s "$pat" ] || echo "install-hooks: WARNING — $pat is absent or empty; every leak check and push fails closed until it is generated" >&2
exit 0
