#!/usr/bin/env bash
# leakcheck.sh — refuse fork commits that carry content from the private
# repository the fork is maintained from. Fails closed. Run inside the fork
# (main clone or a worktree):
#
#   leakcheck.sh [--patterns F] [--range <tip>...]   check these tips
#   leakcheck.sh [--patterns F] --stdin              git's pre-push stdin
#   leakcheck.sh [--patterns F]                      every local ai-sdlc/* branch
#
# The range of a tip is `git rev-list <tip> --not --remotes=upstream <tags>`,
# where <tags> are the v* tags reachable from an upstream ref: only our own
# commits, never upstream's history (a local v* tag on a commit of ours does
# not hide it); for the orphan tooling branch that is the whole branch.
#
# A commit is refused for: a merge; a binary file added or modified (into
# binary); an added file named .env, .env.* or *.env; an author or committer
# email not
# @users.noreply.github.com (allow more with `git config --add
# forkleak.allowEmail <address>`); and, in its message, its added lines
# (`git show -p -U0`) or its paths, any token shape below, an absolute home
# path, or any fixed string of the patterns file.
#
# The patterns file (one fixed string per line, `#` comments) is --patterns,
# else `git config forkleak.patternsFile`. It lives outside the fork and is
# generated by the private repository's tooling. Absent or empty: exit 3.
#
# Output: one line per hit, `leak <commit12> <where> <rule>`, never the
# matched text (a fixed-pattern hit names the pattern's line number). <where>
# is `commit`, `author`, `message`, `path#<i>` (the commit's <i>-th path in
# `git diff-tree` order: the path's name, or an env or binary file) or
# `+path#<i>` (an added line of that path) — never a path itself, since a
# path can be the leak.
# Exit: 0 clean; 1 hits; 2 usage or not a git repository; 3 no patterns.
set -uo pipefail

lk_die() { printf 'leakcheck: %s\n' "$1" >&2; exit "${2:-2}"; }

# Token shapes and home paths. Two are split so this file does not match
# itself; the rest cannot (each needs a character class where its text has `[`).
LK_RULES=(
  "openai-key|sk-[A-Za-z0-9_-]{20,}"
  "langfuse-secret-key|sk-lf-[A-Za-z0-9-]{8,}"
  "langfuse-public-key|pk-lf-[A-Za-z0-9-]{8,}"
  "github-token|gh[pousr]_[A-Za-z0-9]{36}"
  "github-pat|github_pat_[A-Za-z0-9_]{20,}"
  "huggingface-token|hf_[A-Za-z0-9]{30,}"
  "aws-access-key|AKIA[0-9A-Z]{16}"
  "slack-token|xox[abprs]-"
  "private-key|-----BEGIN [A-Z ]*PRIVATE KEY-----"
  "bearer-token|Bearer [A-Za-z0-9._-]{20,}"
  "home-path|/home/[a-z_][a-z0-9_-]*/"
  "mac-home-path|/Use""rs/[^/ ]+/"
  "root-home-path|/ro""ot/"
)

patterns="" mode=all tips=()
while [ $# -gt 0 ]; do
  case "$1" in
    --patterns) [ -n "${2:-}" ] || lk_die "--patterns needs a file"; patterns="$2"; shift 2 ;;
    --stdin) mode=stdin; shift ;;
    --range) mode=range; shift; while [ $# -gt 0 ] && [ "${1#--}" = "$1" ]; do tips+=("$1"); shift; done ;;
    -h|--help) sed -n '2,/^set -uo/p' "${BASH_SOURCE[0]}" | sed '$d; s/^# \{0,1\}//'; exit 0 ;;
    *) lk_die "unknown argument '$1' (leakcheck.sh [--patterns F] [--range <tip>...|--stdin])" ;;
  esac
done
git rev-parse --git-dir >/dev/null 2>&1 || lk_die "not inside a git repository"

[ -n "$patterns" ] || patterns="$(git config --get forkleak.patternsFile 2>/dev/null)"
TMPD="$(mktemp -d)"; trap 'rm -rf "$TMPD"' EXIT
LK_PAT="$TMPD/patterns"
[ -n "$patterns" ] && [ -r "$patterns" ] && grep -v -e '^[[:space:]]*#' -e '^[[:space:]]*$' "$patterns" > "$LK_PAT" 2>/dev/null
if [ ! -s "$LK_PAT" ]; then
  lk_die "no patterns: '${patterns:-forkleak.patternsFile is unset}' is absent or empty — generate it with the private repository's fork-patterns verb, then set forkleak.patternsFile (install-hooks.sh)" 3
fi

case "$mode" in
  stdin) while read -r _lref lsha _rref _rsha; do
           [ -n "${lsha:-}" ] || continue
           case "$lsha" in *[!0]*) tips+=("$lsha") ;; esac   # all zeros: a delete
         done ;;
  range) [ ${#tips[@]} -gt 0 ] || lk_die "--range needs at least one tip" ;;
  all)   while IFS= read -r r; do tips+=("$r"); done < <(git for-each-ref --format='%(refname)' 'refs/heads/ai-sdlc/*') ;;
esac

mapfile -t allow < <(git config --get-all forkleak.allowEmail 2>/dev/null)
HITS=0
hit() { printf 'leak %s %s %s\n' "${1:0:12}" "$2" "$3"; HITS=$((HITS+1)); }

# Scan the file <f> (one item per line) and report each hit at <where>, or at
# `+path#<i>` when <where> is `+` (lines are `<i>\t<text>`, <i> the index).
scan() {  # <commit> <file> <where>
  local c="$1" f="$2" where="$3" r name rx n m pl
  for r in "${LK_RULES[@]}"; do
    name="${r%%|*}"; rx="${r#*|}"
    while IFS=: read -r n _; do
      [ -n "$n" ] || continue
      if [ "$where" = + ]; then hit "$c" "+path#$(sed -n "${n}p" "$f" | cut -f1)" "$name"; else hit "$c" "$where" "$name"; fi
    done < <(if [ "$where" = + ]; then cut -f2- "$f"; else cat "$f"; fi | grep -nE -- "$rx")
  done
  while IFS= read -r n; do
    [ -n "$n" ] || continue
    m="$(sed -n "${n}p" "$f")"; [ "$where" = + ] && m="$(printf '%s' "$m" | cut -f2-)"
    while IFS= read -r pl; do
      if [ "$where" = + ]; then hit "$c" "+path#$(sed -n "${n}p" "$f" | cut -f1)" "patterns:L$pl"; else hit "$c" "$where" "patterns:L$pl"; fi
    done < <(printf '%s\n' "$m" | grep -oF -f "$LK_PAT" | sort -u | while IFS= read -r s; do grep -nxF -- "$s" "$patterns" | head -1 | cut -d: -f1; done)
  done < <(if [ "$where" = + ]; then cut -f2- "$f"; else cat "$f"; fi | grep -nF -f "$LK_PAT" | cut -d: -f1)
}

check_commit() {
  local c="$1" e ok a p i=0 base
  [ "$(git rev-list --parents -n 1 "$c" | wc -w)" -gt 2 ] && hit "$c" commit merge
  for e in "$(git log -1 --format=%ae "$c")" "$(git log -1 --format=%ce "$c")"; do
    ok=0
    case "$e" in *@users.noreply.github.com) ok=1 ;; esac
    for a in "${allow[@]}"; do [ "$e" = "$a" ] && ok=1; done
    [ "$ok" = 1 ] || hit "$c" author non-noreply-email
  done
  git log -1 --format=%B "$c" > "$TMPD/msg"
  scan "$c" "$TMPD/msg" message
  # The commit's paths, indexed 1.. in diff-tree order: raw (-z) for the
  # rules, quoted (as `git show` prints them) to index the added lines. A
  # `+++ ` line is a file name only in a diff header (an added line can read
  # `++ x`).
  local -A idx=()
  local dt=(git diff-tree -r --root --no-commit-id --no-renames)
  "${dt[@]}" --name-only "$c" > "$TMPD/qpaths"
  while IFS= read -r -d '' p; do
    i=$((i+1)); idx["$p"]=$i
    printf '%s\n' "$p" > "$TMPD/path1"; scan "$c" "$TMPD/path1" "path#$i"
  done < <("${dt[@]}" -z --name-only "$c")
  while IFS= read -r -d '' p; do
    base="${p##*/}"
    case "$base" in .env|.env.*|*.env) hit "$c" "path#${idx[$p]:-?}" env-file ;; esac
  done < <("${dt[@]}" -z --diff-filter=A --name-only "$c")
  # Added, modified or type-changed into binary (numstat `-`); a deletion is not.
  while IFS=$'\t' read -r -d '' a _ p; do
    [ "$a" = - ] && hit "$c" "path#${idx[$p]:-?}" binary-file
  done < <("${dt[@]}" -z --diff-filter=AMT --numstat "$c")
  git show -p -U0 --no-renames --format= --root --no-color --no-ext-diff "$c" 2>/dev/null \
    | awk -v qp="$TMPD/qpaths" '
        BEGIN { while ((getline l < qp) > 0) ix[l] = ++k }
        /^diff / { h = 1; next }
        /^@@/ { h = 0; next }
        h && /^\+\+\+ / { f = substr($0, 5); sub(/\t$/, "", f)
                          if (f ~ /^"b\//) f = "\"" substr(f, 4); else sub(/^b\//, "", f)
                          i = (f in ix) ? ix[f] : "?"; next }
        !h && /^\+/ { print i "\t" substr($0, 2) }' > "$TMPD/added"
  scan "$c" "$TMPD/added" +
}

# Upstream's history: its remote-tracking refs, and the v* tags one of them
# reaches (a v* tag that only marks a commit of ours hides nothing).
mapfile -t up < <(git for-each-ref --format='%(refname)' 'refs/remotes/upstream/')
excl=(--remotes=upstream)
while IFS= read -r tg; do
  for u in "${up[@]}"; do
    git merge-base --is-ancestor "$tg^{commit}" "$u" 2>/dev/null && { excl+=("$tg"); break; }
  done
done < <(git for-each-ref --format='%(refname)' 'refs/tags/v*')

n=0
for t in "${tips[@]}"; do
  git rev-parse -q --verify "$t^{commit}" >/dev/null 2>&1 || lk_die "unknown tip '$t'"
  while IFS= read -r c; do check_commit "$c"; n=$((n+1)); done \
    < <(git rev-list --reverse "$t" --not "${excl[@]}")
done
if [ "$HITS" -gt 0 ]; then
  printf 'leakcheck: %s hit(s) in %s commit(s) of our own — refused\n' "$HITS" "$n" >&2; exit 1
fi
printf 'leakcheck: clean — %s commit(s) of our own over %s tip(s) (patterns %s)\n' "$n" "${#tips[@]}" "$(sha256sum < "$patterns" | cut -c1-12)"
